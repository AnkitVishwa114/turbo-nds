package com.appkraft.turbonds.ui

import androidx.compose.ui.unit.dp

/**
 * One spacing scale for the whole app, so every screen lines up: content sits on the same
 * 16 dp edge, sections are 24 dp apart, items inside a section 12 dp apart.
 */
object Dimens {
    val Edge = 16.dp
    val Section = 24.dp
    val Item = 12.dp
    val Tight = 8.dp
    val CardRadius = 18.dp
    val TileRadius = 16.dp
    val TopBarHeight = 56.dp
}
